/* libspectrum.h: the few libspectrum names the lifted Fuse code uses.

   Fuse builds against libspectrum (third_party/libspectrum), whose real
   libspectrum.h is generated by its configure script. The machine and Z80
   core lifted from Fuse only need its integer types and allocation
   wrappers, so they get this header instead (PLAN.md §1.2, Q6). */

#ifndef COMPAT_LIBSPECTRUM_H
#define COMPAT_LIBSPECTRUM_H

#include <stdint.h>
#include <stdlib.h>

typedef uint8_t  libspectrum_byte;
typedef int8_t   libspectrum_signed_byte;
typedef uint16_t libspectrum_word;
typedef int16_t  libspectrum_signed_word;
typedef uint32_t libspectrum_dword;
typedef int32_t  libspectrum_signed_dword;
typedef uint64_t libspectrum_qword;
typedef int64_t  libspectrum_signed_qword;

#define libspectrum_new( type, count )  ( (type *)calloc( (count), sizeof( type ) ) )
#define libspectrum_new0( type, count ) ( (type *)calloc( (count), sizeof( type ) ) )
#define libspectrum_renew( type, mem, count ) \
  ( (type *)realloc( (void *)(mem), (count) * sizeof( type ) ) )
#define libspectrum_free free

#ifdef __GNUC__
#define GCC_UNUSED __attribute__ ((unused))
#else
#define GCC_UNUSED
#endif

#endif /* COMPAT_LIBSPECTRUM_H */
